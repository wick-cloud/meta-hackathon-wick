import { createHash, randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it, vi } from 'vitest';
import type { PoolClient } from 'pg';
import type { Config } from '../src/server/config.js';
import type { Actor } from '../src/shared/types.js';
import { assertDemoInference } from '../src/server/demo/inference-guard.js';
import { demoStudioCommand, demoStudioMessages } from '../src/server/demo/studio-script.js';
import { inputReservation, type RuntimeRoute } from '../src/server/inference/runtime.js';
import { localStudioRunner } from './fixtures/demo-studio-runner.js';

const source = "print('Hello, World!')\n";
const deadline = () => new Date(Date.now() + 60_000).toISOString();
const digest = (text: string) => createHash('sha256').update(text).digest('hex');

describe('guided Studio prompt and actual restricted Python runner', () => {
  it('fits both fixed prompts inside real UTF-8 accounting and leaves room for the preceding call', () => {
    const route = {
      mode: 'real',
      inputAccounting: 'utf8-bytes-v1',
      inputBound: 100_000,
    } as RuntimeRoute;
    for (const attempt of [0, 1] as const) {
      const reservation = inputReservation(route, { messages: demoStudioMessages(attempt) });
      expect(reservation).toBeGreaterThanOrEqual(4128);
      expect(reservation).toBeLessThan(4500);
      // A second call is admitted only after real settlement; the fixed prompt
      // leaves at least 500 input tokens for the prior receipt, not a refill.
      expect(5000 - reservation).toBeGreaterThan(500);
    }
  });

  it('writes the exact generated source and executes it in a real child Python process', () => {
    const runner = localStudioRunner(),
      id = randomUUID();
    try {
      const generated = 'print ("Hello, World!")\n';
      const result = runner.execute(demoStudioCommand(id, 0, generated, deadline()));
      expect(result).toEqual({
        runId: id,
        attempt: 0,
        sha256: digest(generated),
        valid: true,
        stdout: 'Hello, World!\n',
        exitCode: 0,
        errorCode: null,
      });
      expect(readFileSync(join(runner.directory, 'hello_world.py'), 'utf8')).toBe(generated);
      expect(
        execFileSync('python3', ['-I', '-S', join(runner.directory, 'hello_world.py')], {
          encoding: 'utf8',
          timeout: 5000,
        }),
      ).toBe('Hello, World!\n');
      expect(readFileSync(join(runner.directory, `.wick-studio-${id}-0.json`), 'utf8')).toContain(
        digest(generated),
      );
    } finally {
      runner.close();
    }
  });

  it('rejects escape syntax before writing or executing generated bytes', () => {
    const rejected = [
      "import os\nprint('Hello, World!')",
      "__import__('os').system('id')",
      "print.__call__('Hello, World!')",
      "p=print\np('Hello, World!')",
      "print('Hello, World!', flush=True)",
      "print(*['Hello, World!'])",
      "for x in range(1): print('Hello, World!')",
      "print('Hello, World!'); print('second')",
      "print(f'Hello, World!')",
      "print('Hello, ' + 'World!')",
      "print('wrong output')",
      String.raw`# coding: unicode_escape
print("Hello, World!")
# \u000aprint("unexpected")`,
      '# coding: latin-1\nprint("Hello, World!")\n',
      '# coding: utf-7\nprint("Hello, World!")\n',
      "print('Hello, World!')\n" + '#'.repeat(260),
    ];
    const runner = localStudioRunner();
    try {
      for (const generated of rejected) {
        const result = runner.execute(demoStudioCommand(randomUUID(), 0, generated, deadline()));
        expect(result).toMatchObject({
          valid: false,
          stdout: '',
          exitCode: null,
          errorCode: 'invalid_source',
        });
      }
      expect(existsSync(join(runner.directory, 'hello_world.py'))).toBe(false);
    } finally {
      runner.close();
    }
  });

  it('treats a completed writable journal as a no-reexecution marker, never trusted verification', () => {
    const runner = localStudioRunner(),
      id = randomUUID();
    try {
      const command = demoStudioCommand(id, 0, source, deadline());
      expect(runner.execute(command).exitCode).toBe(0);
      writeFileSync(join(runner.directory, 'hello_world.py'), '# user edit after verification\n');
      expect(runner.execute(command)).toMatchObject({ stdout: '', exitCode: null });
      expect(runner.execute(command).errorCode).not.toBeNull();
      expect(readFileSync(join(runner.directory, 'hello_world.py'), 'utf8')).toContain('user edit');
      expect(
        runner.execute(demoStudioCommand(id, 0, 'print("Hello, World!")\n', deadline())),
      ).toMatchObject({ stdout: '', exitCode: null });
    } finally {
      runner.close();
    }
  });

  it('rejects a forged passing receipt in the guest-writable workspace', () => {
    const runner = localStudioRunner(),
      id = randomUUID();
    try {
      writeFileSync(
        join(runner.directory, `.wick-studio-${id}-0.json`),
        JSON.stringify({
          runId: id,
          attempt: 0,
          sha256: digest(source),
          valid: true,
          stdout: 'Hello, World!\n',
          exitCode: 0,
          errorCode: null,
        }),
      );
      const receipt = runner.execute(demoStudioCommand(id, 0, source, deadline()));
      expect(receipt).toMatchObject({ stdout: '', exitCode: null });
      expect(receipt.errorCode).not.toBeNull();
      expect(existsSync(join(runner.directory, 'hello_world.py'))).toBe(false);
    } finally {
      runner.close();
    }
  });

  it.each(['fifo', 'dangling symlink'])(
    'rejects a journal %s without opening or following it',
    (kind) => {
      const runner = localStudioRunner(),
        id = randomUUID();
      try {
        const journal = join(runner.directory, `.wick-studio-${id}-0.json`);
        if (kind === 'fifo')
          execFileSync(
            'python3',
            ['-I', '-S', '-c', 'import os,sys;os.mkfifo(sys.argv[1])', journal],
            { timeout: 5000 },
          );
        else symlinkSync(join(runner.directory, 'missing-journal-target'), journal);
        expect(runner.execute(demoStudioCommand(id, 0, source, deadline()))).toMatchObject({
          stdout: '',
          exitCode: null,
          errorCode: 'execution_already_recorded',
        });
        expect(existsSync(join(runner.directory, 'hello_world.py'))).toBe(false);
      } finally {
        runner.close();
      }
    },
  );

  it('does not execute uncertain or expired attempts, or follow an artifact symlink', () => {
    const runner = localStudioRunner(),
      pendingId = randomUUID();
    try {
      writeFileSync(join(runner.directory, `.wick-studio-${pendingId}-0.pending`), digest(source));
      expect(runner.execute(demoStudioCommand(pendingId, 0, source, deadline()))).toMatchObject({
        errorCode: 'execution_unknown',
        stdout: '',
        exitCode: null,
      });
      expect(
        runner.execute(demoStudioCommand(randomUUID(), 0, source, new Date(1).toISOString())),
      ).toMatchObject({ errorCode: 'deadline_expired', stdout: '', exitCode: null });
      expect(existsSync(join(runner.directory, 'hello_world.py'))).toBe(false);
      const outside = join(runner.directory, 'outside.txt');
      writeFileSync(outside, 'must stay unchanged');
      symlinkSync(outside, join(runner.directory, 'hello_world.py'));
      expect(runner.execute(demoStudioCommand(randomUUID(), 0, source, deadline())).exitCode).toBe(
        0,
      );
      expect(readFileSync(outside, 'utf8')).toBe('must stay unchanged');
      expect(readFileSync(join(runner.directory, 'hello_world.py'), 'utf8')).toBe(source);
    } finally {
      runner.close();
    }
  });

  it('rejects an internal guided source with no demo run while leaving ordinary grants outside the demo guard', async () => {
    const db = { query: vi.fn(async () => ({ rows: [] })) } as unknown as PoolClient;
    const actor = { id: randomUUID(), role: 'buyer' } as Actor;
    const config = { liveDemoEnabled: true } as Config;
    await expect(
      assertDemoInference(db, config, actor, randomUUID(), 1024, true, {
        id: randomUUID(),
        leaseToken: randomUUID(),
        packId: randomUUID(),
        planAttempt: 0,
      }),
    ).rejects.toMatchObject({ statusCode: 403 });
    await expect(
      assertDemoInference(db, config, actor, randomUUID(), 1024, true),
    ).resolves.toBeUndefined();
  });
});
